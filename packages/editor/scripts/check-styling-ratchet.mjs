#!/usr/bin/env node
/**
 * Styling-mechanism ratchet — one component system, enforced.
 *
 * The editor styles chrome five different ways: literal `style={{}}`, hoisted
 * `style={someConst}`, `tw:` utility classes, 30 hand-written CSS files, and
 * chrome-ui components. Changing how a panel looks means first working out
 * WHICH of the five owns it. That is the actual reason changes are slow — not
 * the token layer, which is one namespace (--bk-*, 166 tokens, 1 ghost).
 *
 * The target is chrome-ui components + `tw:` utilities. The other three are
 * being drained. This gate locks the count so a drain can never silently
 * reverse: the numbers may go DOWN or stay flat, never up.
 *
 * `tw:` classes and chrome-ui components are deliberately NOT counted — those
 * are the destination, and capping them would fight the migration.
 *
 * Baseline lives in scripts/.styling-baseline.json. Lower it when you drain;
 * never raise it. Raising it is the thing this file exists to prevent.
 *
 * TWO CORRECTIONS, 2026-08-02 (/autoplan CEO phase — both voices flagged them
 * independently, and both were real):
 *
 *  1. `css_lines` used to walk all of src/editor, so it counted 1,431 lines the
 *     plan itself declares permanently out of scope: Canvas.css and the canvas
 *     overlays (they style the CUSTOMER's runtime-generated HTML), the
 *     site-builder design tokens (the customer's published page), and — the
 *     one nobody noticed — chrome-ui's OWN skeleton.css + slider.css, i.e. the
 *     destination library. The number therefore had a floor of ~1,431 and
 *     could never reach zero. A gate locked at a number nobody can move gets
 *     `--update`d past and stops meaning anything.
 *
 *  2. Three aggregate totals cannot see direction. A panel could add 40 fresh
 *     CSS lines while another deleted 40 and the gate stayed green — a ratchet
 *     on totals, not on architecture. `css_files` now locks EVERY in-scope
 *     file individually, so growth anywhere fails even when the total falls.
 *
 * @license BSD-3-Clause
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = join(HERE, "..", "src", "editor");
const BASELINE_PATH = join(HERE, ".styling-baseline.json");

/** CSS that is NOT panel chrome, each with the structural reason it stays.
 *  Matched against the src-relative path. Adding a row here is a scope
 *  decision — say why, or the next reader cannot tell an exception from a
 *  leak. */
const CSS_OUT_OF_SCOPE = [
  [/^canvas\//, "styles the CUSTOMER's HTML, generated by the engine at runtime"],
  [/^design-system\//, "the customer's published site, not editor chrome"],
  [/^chrome-ui\//, "the destination library's own two files"],
];

const outOfScope = (rel) => CSS_OUT_OF_SCOPE.find(([re]) => re.test(rel));

function walk(dir, out = []) {
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) {
      if (e !== "__tests__") walk(p, out);
    } else out.push(p);
  }
  return out;
}

function measure() {
  let inline_literal = 0;
  let inline_hoisted = 0;
  let css_lines = 0;
  const css_files = {};
  const excluded = [];
  const worst = [];
  for (const p of walk(SRC)) {
    if (p.endsWith(".tsx")) {
      const s = readFileSync(p, "utf8");
      const lit = (s.match(/style=\{\{/g) || []).length;
      // `style={foo}` / `style={styles.bar}` — the hoisted CSSProperties
      // pattern. Excludes `style={{` by requiring a non-brace first char.
      const hoi = (s.match(/style=\{[a-zA-Z_$][^{]/g) || []).length;
      inline_literal += lit;
      inline_hoisted += hoi;
      if (lit + hoi > 0) worst.push([lit + hoi, p.slice(p.indexOf("/src/") + 1)]);
    } else if (p.endsWith(".css")) {
      const rel = relative(SRC, p);
      const n = readFileSync(p, "utf8").split("\n").length;
      const why = outOfScope(rel);
      if (why) {
        excluded.push([n, rel, why[1]]);
        continue;
      }
      css_lines += n;
      css_files[rel] = n;
    }
  }
  worst.sort((a, b) => b[0] - a[0]);
  excluded.sort((a, b) => b[0] - a[0]);
  return { inline_literal, inline_hoisted, css_lines, css_files, worst, excluded };
}

const now = measure();
const base = JSON.parse(readFileSync(BASELINE_PATH, "utf8"));

if (process.argv.includes("--update")) {
  writeFileSync(
    BASELINE_PATH,
    JSON.stringify(
      {
        inline_literal: now.inline_literal,
        inline_hoisted: now.inline_hoisted,
        css_lines: now.css_lines,
        css_files: now.css_files,
      },
      null,
      2,
    ) + "\n",
  );
  console.log("[styling-ratchet] baseline updated:", now.inline_literal, now.inline_hoisted, now.css_lines);
  process.exit(0);
}

if (process.argv.includes("--top")) {
  console.log("Heaviest remaining files (literal + hoisted inline styles):");
  for (const [n, p] of now.worst.slice(0, 30)) console.log(`  ${String(n).padStart(3)}  ${p}`);
  console.log("\nIn-scope CSS, largest first:");
  for (const [p, n] of Object.entries(now.css_files).sort((a, b) => b[1] - a[1]).slice(0, 20)) {
    console.log(`  ${String(n).padStart(5)}  ${p}`);
  }
  console.log("\nExcluded from css_lines (NOT a target):");
  for (const [n, p, why] of now.excluded) console.log(`  ${String(n).padStart(5)}  ${p}\n         ${why}`);
  process.exit(0);
}

let failed = false;
for (const key of ["inline_literal", "inline_hoisted", "css_lines"]) {
  const delta = now[key] - base[key];
  const label = key.padEnd(15);
  if (delta > 0) {
    console.error(`[styling-ratchet] FAIL ${label} ${now[key]} > baseline ${base[key]} (+${delta})`);
    failed = true;
  } else {
    console.log(`[styling-ratchet] ok   ${label} ${now[key]} (baseline ${base[key]}${delta < 0 ? `, drained ${-delta}` : ""})`);
  }
}

/* Per-file lock. The aggregate alone cannot see direction: 40 lines added in
   one panel and 40 removed from another nets to zero and passes. A NEW in-scope
   CSS file is the same violation with a different shape, so an unknown path is
   a failure, not a free pass. */
if (!base.css_files) {
  console.error("[styling-ratchet] FAIL — baseline has no css_files map. Run --update.");
  failed = true;
} else {
  for (const [p, n] of Object.entries(now.css_files)) {
    const was = base.css_files[p];
    if (was === undefined) {
      console.error(`[styling-ratchet] FAIL new panel CSS file: ${p} (${n} lines)`);
      failed = true;
    } else if (n > was) {
      console.error(`[styling-ratchet] FAIL ${p} grew ${was} -> ${n} (+${n - was})`);
      failed = true;
    }
  }
}

if (failed) {
  console.error("");
  console.error("New inline styles or CSS lines were added to editor chrome.");
  console.error("Target is a chrome-ui component styled with `tw:` utilities.");
  console.error("Genuinely computed values (drag position, measured size) are the");
  console.error("one exception CLAUDE.md allows — put those in a canvas overlay.");
  console.error("See `node scripts/check-styling-ratchet.mjs --top` for the worst files,");
  console.error("the in-scope CSS list, and what is excluded and why.");
  process.exit(1);
}
console.log(
  `[styling-ratchet] PASS — one-component-system drain holding ` +
    `(${Object.keys(now.css_files).length} in-scope CSS files, ` +
    `${now.excluded.reduce((a, [n]) => a + n, 0)} lines excluded by scope)`,
);
