// --- Sub-hook result interfaces ---

export interface LibraryStateResult {
  /**
   * How far the server pull got: the cursor for the next page (null when the
   * library is fully on screen) and how many assets exist in total. Null until
   * the first page lands — or forever in the standalone demo, which has no
   * server to page.
   */
  serverPage: { nextCursor: string | null; total: number; loaded: number } | null;
  /**
   * Where a whole-library search stands. `truncated` means the SEARCH itself
   * was paged and only its first page is in hand; `failed` means the server leg
   * did not come back, which must never be shown as "no match".
   */
  searchState: "idle" | "searching" | "whole" | "truncated" | "failed";
  loadingMore: boolean;
  /** The last "Load more" did not come back. Offered as a retry, not a toast. */
  loadMoreError: boolean;
  loadMoreAssets(): Promise<void>;
  /** False only once storage has been read — see useLibraryState. */
  libraryLoading: boolean;
  /** Non-null when storage could not be read at all. NOT the same as empty. */
  libraryError: string | null;
  retryLibraryLoad(): void;
  rawAssets: MediaAsset[];
  libraryItems: LibraryItem[];
  folders: MediaFolder[];
  allFolders: MediaFolder[];
  currentFolderId: string | null;
  setCurrentFolderId(id: string | null): void;
  createFolder(name: string): Promise<void>;
  inspectFolder(id: string): { assetCount: number; subFolderCount: number };
  deleteFolder(id: string, options?: { force?: boolean }): Promise<void>;
  moveAsset(assetId: string, folderId: string | null): Promise<void>;
  bulkMoveAssets(assetIds: string[], folderId: string | null): Promise<void>;
  counts: TypeCounts;
  sort: MediaSortBy;
  sortDir: SortDirection;
  gridN: 2 | 3 | 4;
  fmtFilter: string;
  activeType: MediaTypeFilter;
  activeTypes: ReadonlySet<MediaBucket>;
  librarySearch: string;
  setLibrarySearch(q: string): void;
  setSort(by: MediaSortBy, dir: SortDirection): void;
  setGridN(n: 2 | 3 | 4): void;
  setFmtFilter(f: string): void;
  setActiveType(t: MediaTypeFilter): void;
  toggleType(t: MediaBucket): void;
  renameItem(key: string, name: string): Promise<void>;
  renameFolder(id: string, name: string): Promise<void>;
  updateItem(key: string, updates: Partial<LibraryItem>): Promise<void>;
}

