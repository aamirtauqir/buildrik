/** A library item (maps MediaAsset to display-ready shape) */
export interface LibraryItem {
  key: string;
  name: string;
  /** Label with the file extension restored — board 144:2 draws full filenames. */
  displayName?: string;
  type: "img" | "vid" | "ico" | "fnt";
  src: string;
  thumb?: string;
  size: number; // bytes
  duration?: number; // seconds, video only
  width?: number;
  height?: number;
  altText?: string;
  /**
   * P7 — provenance for AI-generated alt text. When present, the panel
   * shows "AI-generated by {model} on {date}" + a Regenerate button.
   */
  generatedAltMeta?: {
    generatedAt: string;
    model: string;
  };
  createdAt: string;
  mimeType: string;
  assetSource?: "uploaded" | "stock" | "ai";
  /**
   * Dashboard MediaAsset id (the synced server row). Present once the asset
   * has been uploaded + synced; absent for local-only / stock items. Used to
   * read & write the server-side version history (media.{list,create,restore}
   * AssetVersion) from the detail drawer's Versions tab.
   */
  assetId?: string;
}

